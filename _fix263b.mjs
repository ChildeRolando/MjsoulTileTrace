import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const sha=b=>createHash('sha256').update(b).digest('hex');
const p='E:/AgentData/Coach/knowledge/processing/production/sol-high-field-repair12-20261027-p263/candidates/79-cn/page-0263.json';
const c=JSON.parse(await readFile(p,'utf8'));
const fig=c.figures.find(f=>f.figureId==='79-cn-p263-r1');
const from='局况：南4局，0本场；中央立直棒计数为0本。宝牌指示牌：2s。';
const to='局况：南4局，0本场；中央立直棒计数为0本。“ドラ”栏显示2s；本图无法确认其表示实际宝牌还是宝牌指示牌。';
const n=fig.transcription.split(from).length-1;
if(n!==1) throw new Error('occurrences_'+n);
fig.transcription=fig.transcription.replace(from,to);
if(!Array.isArray(fig.unknowns)) throw new Error('unknowns_not_array');
fig.unknowns=[...fig.unknowns,'“ドラ”栏显示的2s未标明是实际宝牌还是宝牌指示牌，本页无法确定。'];
const cp={...c};delete cp.candidateSha256;
c.candidateSha256=sha(JSON.stringify(cp));
const out=JSON.stringify(c,null,2)+'\n';
await writeFile(p,out);
console.log('unknowns', JSON.stringify(fig.unknowns, null, 0));
console.log('new_file_sha256', sha(Buffer.from(out)));
